# ==========================================
# 1. HELPER: METRIC MATH
# ==========================================
def calculate_f1(pred_list, gt_set):
    if not pred_list or not gt_set: return 0.0, 0.0, 0.0
    
    # Intersection of objects/facts
    hits = len(set(pred_list).intersection(gt_set))
    
    precision = hits / len(pred_list)
    recall = hits / len(gt_set)
    
    if (precision + recall) == 0: return 0.0, 0.0, 0.0
    f1 = 2 * (precision * recall) / (precision + recall)
    return precision, recall, f1

def calculate_map(pred_list, gt_set):
    if not gt_set: return 0.0
    hits = 0
    sum_precisions = 0
    
    for i, item in enumerate(pred_list):
        if item in gt_set:
            hits += 1
            sum_precisions += hits / (i + 1)
            
    return sum_precisions / len(gt_set)

def calculate_ndcg(pred_list, gt_set, k=5):
    if not gt_set: return 0.0
    
    # Binary relevance: 1 if in GT, 0 if not
    relevance = [1 if item in gt_set else 0 for item in pred_list]
    
    # Pad with 0s if prediction is shorter than k
    if len(relevance) < k:
        relevance += [0] * (k - len(relevance))
    relevance = relevance[:k]
    
    # Ideal DCG (Perfect sorting)
    ideal = sorted(relevance, reverse=True)
    
    if sum(ideal) == 0: return 0.0
    return ndcg_score([ideal], [relevance], k=k)

