def load_predictions(summary_file):
    """Parses the output.txt files generated by H-IRES."""
    preds = {}
    current_entity = None
    
    if not os.path.exists(summary_file):
        print(f"   [Warning] Summary file not found: {summary_file}")
        return {}

    with open(summary_file, 'r') as f:
        for line in f:
            line = line.strip()
            # Detect Entity Header
            if line.startswith("ENTITY:") or line.startswith("[Entity]:"):
                # Clean up the line to get just the URI
                current_entity = line.split(": ", 1)[-1].strip()
                preds[current_entity] = []
            # Detect Summary Lines (Facts)
            elif line.startswith("->"):
                if current_entity:
                    fact = line.replace("-> ", "").strip()
                    preds[current_entity].append(fact)
    return preds

def load_wikies_ground_truth(base_path):
    """Loads Ground Truth from WIKIES CSVs (using Test/Val files as Gold Standard)."""
    gt = {}
    # We look for files ending in 'test.csv' or 'val.csv'
    for root, dirs, files in os.walk(base_path):
        for file in files:
            if "test.csv" in file or "val.csv" in file:
                path = os.path.join(root, file)
                try:
                    with open(path, 'r', encoding='utf-8', errors='ignore') as f:
                        reader = csv.reader(f)
                        for row in reader:
                            if len(row) >= 3:
                                subj, _, obj = row[0], row[1], row[2]
                                if subj not in gt: gt[subj] = set()
                                gt[subj].add(obj)
                except: continue
    return gt

